//Loops in JavaScript

//for Loop
for (let i = 1; i <= 10; i++) {
  console.log("I am learning Javascript");
}

let product = 1;
for (let i = 1; i <= 5; i++) {
  product = product * i;
}
console.log(product);

for (let i = 1; i <= 10; i++) {
  console.log(5 * i);
}

//while loop

let x = 1;
while (x <= 6) {
  console.log("Pakistan");
  x++;
}

let j = 1;
do {
  console.log("I am watching Stranger Things");
  j++;
} while (j <= 5);
