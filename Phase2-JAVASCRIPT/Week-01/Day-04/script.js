//Arithmatic Operators
let a = 10;
let b = 6;
console.log(a + b); //aditional operator
console.log(a - b); //subtract operator
console.log(a * b); //multiplication operator
console.log(a / b); //divide operator
console.log(a % b); //modulus operator
console.log(a ** b); //exponential operator

//Uniary Operators
let c = 6;
let d = 7;
console.log(++c); //increment operator
console.log(--d); //decreament operator

//Comparison Operators
let e = 5;
let f = 10;
console.log(e == f); //false
console.log(e != f); //true
console.log(e < f); //true
console.log(e > f); //false
console.log(e <= f); //true
console.log(e >= f); //false

//Logical Operators
//&& (and) operator gives true only if both the values are true
const hasEmail = true;
const hasPassword = false;
console.log(hasEmail && hasPassword); //false
console.log(!hasEmail); //false

// || (or) operator gives true if any of the value is true
const hasCredit = true;
const hasVouchers = false;
console.log(hasCredit || hasVouchers); //true
